"""Run the expert feedback loop over cached candidates (data/candidates.json) and measure before/after per domain.

Arms, each scored by the SIMULATED expert on held-out tasks:
  baseline       open model alone, plain prompt, greedy
  taught_prompt  expert rules + the expert's policy-checker facts in the prompt, greedy
  reranked       best of n sampled taught answers, chosen by a reranker trained on expert preference pairs
  reranked+guard the reranked answer passed through the expert rules as an output guard
  decision_tool  the expert's policy checker owns the YES/NO; the model only explains; then the guard
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from .review import SimulatedExpert, decision, judge
from .rules import DOMAINS, guard, load, violations
from .tasks import make
from .tune import FEATS, features, pick, train

ROOT = Path(__file__).resolve().parents[3]
CANDIDATES = ROOT / "data" / "candidates.json"
ARMS = ("baseline", "taught_prompt", "reranked", "reranked+guard", "decision_tool")


def with_decision(answer: str, expected: str) -> str:
    body = re.sub(r"^\W*(yes|no)\b[\s.,:;!-]*", "", answer.strip(), flags=re.I)
    return f"{expected}. {body}".strip()


def run(cands: dict | None = None, train_frac: float = 0.5) -> dict:
    cands = cands or json.loads(CANDIDATES.read_text())
    out = {"label": "SIMULATED experts on SYNTHETIC tasks; candidates generated by a real local open model on CPU", "generator": cands["generator"], "domains": {}}
    for dom in DOMAINS:
        pack = load(dom)
        expert = SimulatedExpert(pack)
        items = [c for c in cands["items"] if c["domain"] == dom]
        checker = {t.id: t.expected for t in make(dom, len(items))}  # the expert's policy checker, recomputed from the policy
        cut = int(len(items) * train_frac)
        tr, te = items[:cut], items[cut:]
        pairs, reviews = [], {"approve": 0, "fix": 0, "reject": 0}
        for it in tr:
            pool = [it["baseline"], it["rules_greedy"], *it["rules_samples"]]
            fs = [features(pack, it["prompt"], a, pool) for a in pool]
            recs = [expert.review(it, a) for a in pool]
            for r in recs:
                reviews[r.verdict] += 1
            good = [f for f, r in zip(fs, recs, strict=True) if r.verdict == "approve"]
            bad = [f for f, r in zip(fs, recs, strict=True) if r.verdict != "approve"]
            fixes = [r.fix for r in recs if r.fix]
            if not good and fixes:  # no acceptable sample: the expert's fix becomes the chosen side
                good = [features(pack, it["prompt"], fixes[0], pool)]
            pairs += [(g, b) for g in good for b in bad]
        w = train(pairs)
        arms: dict[str, list[str]] = {a: [] for a in ARMS}
        for it in te:
            pool = [it["rules_greedy"], *it["rules_samples"]]
            best = pool[pick(w, [features(pack, it["prompt"], a, pool) for a in pool])]
            arms["baseline"].append(it["baseline"])
            arms["taught_prompt"].append(it["rules_greedy"])
            arms["reranked"].append(best)
            arms["reranked+guard"].append(guard(pack, best, it["prompt"]))
            arms["decision_tool"].append(guard(pack, with_decision(best, checker[it["id"]]), it["prompt"]))
        acc = {a: round(sum(judge(pack, it, x)[0] for it, x in zip(te, xs, strict=True)) / len(te), 4) for a, xs in arms.items()}
        dec = {a: round(sum(decision(x) == it["expected"] for it, x in zip(te, xs, strict=True)) / len(te), 4) for a, xs in arms.items()}
        bad = {a: sum(bool(violations(pack, x, it["prompt"])) for it, x in zip(te, xs, strict=True)) for a, xs in arms.items()}
        out["domains"][dom] = {
            "expert": pack["expert"],
            "train_tasks": len(tr),
            "test_tasks": len(te),
            "preference_pairs": len(pairs),
            "reviews": reviews,
            "accepted_by_expert": acc,
            "decision_correct": dec,
            "rule_violations": bad,
            "reranker_weights": dict(zip(FEATS, [round(x, 3) for x in w], strict=True)),
        }
    return out
